#!/usr/bin/env node
/**
 * Regenerate the inline icon sprite in public/agent-ui.html from lucide-static.
 *
 * The web UI is a single self-contained document that must work with no network
 * access and under a strict CSP, so icons are inlined as <symbol> definitions
 * instead of loaded from a CDN or an external sprite file (an external <use>
 * href would be fetched as a subresource and blocked by `default-src 'none'`).
 *
 * Only the icons listed below are emitted, so the sprite stays tree-shaken.
 * Run after changing ICONS:  npm run ui:icons
 */
import { readFile, writeFile } from 'fs/promises';
import path from 'path';
import { fileURLToPath } from 'url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const TARGET = path.join(root, 'public', 'agent-ui.html');
const ICON_DIR = path.join(root, 'node_modules', 'lucide-static', 'icons');
const START = '<!-- ICONS:START -->';
const END = '<!-- ICONS:END -->';

const ICONS = [
  'square-pen', 'search', 'image', 'history', 'circle-help', 'chevron-down',
  'chevron-right', 'chevron-up', 'sliders-horizontal', 'chart-column', 'x', 'plus', 'arrow-up',
  'database', 'rotate-ccw', 'paperclip', 'bot', 'terminal', 'copy', 'check',
  'trash-2', 'download', 'loader-circle', 'wrench', 'circle-check',
  'circle-alert', 'file-code', 'message-square', 'panel-left', 'refresh-cw',
  'info', 'settings', 'sparkles', 'user',
  // added for the collapsible sidebar, theming, docs and the activity feed
  'panel-left-close', 'panel-left-open', 'sun', 'moon', 'book-open', 'brain',
  'file', 'wand-sparkles', 'activity', 'circle-dollar-sign', 'gauge',
];

function inner(svg, name) {
  const open = svg.indexOf('>', svg.indexOf('<svg'));
  const close = svg.lastIndexOf('</svg>');
  if (open === -1 || close === -1) throw new Error(`malformed svg for ${name}`);
  return svg.slice(open + 1, close).replace(/\s+/g, ' ').trim();
}

const symbols = [];
for (const name of ICONS) {
  let raw;
  try {
    raw = await readFile(path.join(ICON_DIR, `${name}.svg`), 'utf8');
  } catch {
    throw new Error(`lucide-static has no icon named "${name}" (checked ${ICON_DIR})`);
  }
  symbols.push(`<symbol id="i-${name}" viewBox="0 0 24 24">${inner(raw, name)}</symbol>`);
}

const block = [
  START,
  '<!-- Generated by scripts/build-ui-icons.mjs from lucide-static (ISC). Do not edit by hand. -->',
  '<svg class="sprite" aria-hidden="true" xmlns="http://www.w3.org/2000/svg">',
  ...symbols.map(s => '  ' + s),
  '</svg>',
  END,
].join('\n');

const html = await readFile(TARGET, 'utf8');
const from = html.indexOf(START);
const to = html.indexOf(END);
if (from === -1 || to === -1) throw new Error(`markers ${START} / ${END} not found in ${TARGET}`);

const next = html.slice(0, from) + block + html.slice(to + END.length);
await writeFile(TARGET, next);
console.log(`Wrote ${ICONS.length} icons into ${path.relative(root, TARGET)}`);
